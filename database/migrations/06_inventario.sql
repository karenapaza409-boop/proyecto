SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE n NUMBER;
 PROCEDURE agregar(nombre VARCHAR2,definicion VARCHAR2) IS BEGIN
 SELECT COUNT(*) INTO n FROM all_tab_columns WHERE owner='MM_CATALOGO' AND table_name='PRODUCTOS' AND column_name=nombre;
 IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE MM_CATALOGO.PRODUCTOS ADD ('||definicion||')'; END IF; END;
BEGIN
 agregar('CODIGO_BARRAS','codigo_barras VARCHAR2(50 CHAR)');
 agregar('UNIDAD_VENTA','unidad_venta VARCHAR2(10 CHAR)');
 agregar('STOCK_MINIMO','stock_minimo NUMBER(10)');
END;
/
DECLARE n NUMBER; BEGIN
 SELECT COUNT(*) INTO n FROM (SELECT codigo_barras FROM MM_CATALOGO.PRODUCTOS WHERE codigo_barras IS NOT NULL GROUP BY codigo_barras HAVING COUNT(*)>1);
 IF n>0 THEN RAISE_APPLICATION_ERROR(-20061,'Hay códigos de barras duplicados. Revisar manualmente, no se eliminan registros.'); END IF;
 SELECT COUNT(*) INTO n FROM all_indexes WHERE owner='MM_CATALOGO' AND index_name='UQ_PRODUCTO_BARRAS';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX MM_CATALOGO.UQ_PRODUCTO_BARRAS ON MM_CATALOGO.PRODUCTOS(codigo_barras)'; END IF;
 SELECT COUNT(*) INTO n FROM all_tables WHERE owner='MM_CATALOGO' AND table_name='MOVIMIENTOS_STOCK';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE MM_CATALOGO.MOVIMIENTOS_STOCK (
 id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 producto_id NUMBER(19) NOT NULL REFERENCES MM_CATALOGO.PRODUCTOS(id),
 fecha TIMESTAMP NOT NULL,tipo VARCHAR2(30 CHAR) NOT NULL,referencia VARCHAR2(100 CHAR) NOT NULL,
 cantidad NUMBER(10) NOT NULL,saldo NUMBER(10) NOT NULL CHECK(saldo>=0),actor VARCHAR2(100 CHAR) NOT NULL,motivo VARCHAR2(500 CHAR) NOT NULL)'; END IF;
 SELECT COUNT(*) INTO n FROM all_indexes WHERE owner='MM_CATALOGO' AND index_name='IX_MOV_PRODUCTO';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX MM_CATALOGO.IX_MOV_PRODUCTO ON MM_CATALOGO.MOVIMIENTOS_STOCK(producto_id,id)'; END IF;
END;
/
-- Saldo real al iniciar seguimiento, no reconstrucción de operaciones históricas.
INSERT INTO MM_CATALOGO.MOVIMIENTOS_STOCK(producto_id,fecha,tipo,referencia,cantidad,saldo,actor,motivo)
SELECT p.id,SYSTIMESTAMP,'SALDO_INICIAL','MIG-06',p.stock,p.stock,'SISTEMA_MIGRACION','Saldo observado al iniciar seguimiento; historial anterior no reconstruido'
FROM MM_CATALOGO.PRODUCTOS p WHERE NOT EXISTS(SELECT 1 FROM MM_CATALOGO.MOVIMIENTOS_STOCK m WHERE m.producto_id=p.id);
GRANT SELECT,INSERT,UPDATE,DELETE ON MM_CATALOGO.MOVIMIENTOS_STOCK TO CANTOMODA_APP;
COMMIT;
